"""The README that travels with an export bundle.

It names every file, states the CRS and units, explains the mesh local origin,
and carries the data licences, with the ODbL share-alike notice whenever an
OpenStreetMap-derived layer is in the bundle.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import sce

from ..types import LayerResult
from .dossier import sources_of

FILE_NOTES = {
    "README.txt": "This file.",
    "dossier.json": "Machine-readable record: AOI, every metric, per-layer provenance, sources.",
    "georef.json": "CRS (WKT), bounds, WGS84 centre and the local origin used by glb/obj.",
    "georef.prj": "The CRS as ESRI WKT, for GIS software that wants a .prj.",
    ".pdf": "A3 site context sheet.",
    ".png": "Raster of the site context sheet.",
    ".dxf": "CAD drawing in projected metres (real-world coordinates).",
    ".3dm": "Rhino model in projected metres (real-world coordinates).",
    ".gpkg": "GeoPackage of all vector layers in projected metres, with metrics.",
    ".qml": "QGIS style for the GeoPackage layer of the same name.",
    ".geojson": "Vector layers in WGS84 (RFC 7946).",
    ".svg": "Vector drawing in projected metres.",
    ".glb": "3D mesh, metres, local origin (see georef.json), glTF Y-up.",
    ".obj": "3D mesh, metres, local origin (see georef.json), Z-up.",
    ".mtl": "Materials for the .obj.",
    ".epw": "EnergyPlus weather file (typical year from ERA5) for Ladybug, Honeybee, EnergyPlus.",
}

ODBL_NOTICE = (
    "Contains data (c) OpenStreetMap contributors, available under the Open Database\n"
    "Licence (ODbL) 1.0: https://www.openstreetmap.org/copyright. Exports containing\n"
    "OSM-derived layers are produced works and must keep this attribution and be\n"
    "shared under the same licence when redistributed."
)


def uses_odbl(sources: list[dict[str, Any]]) -> bool:
    """True when any source is OpenStreetMap-derived (ODbL share-alike applies)."""
    return any("odbl" in s["licence"].lower() or "openstreetmap" in s["name"].lower() for s in sources)


def readme_text(aoi: Any, layers: dict[str, LayerResult], names: list[str]) -> str:
    """README body for a bundle of `names` exported for `aoi`."""
    lon, lat = aoi.centroid_lonlat
    edge = 2 * (aoi.radius_m or 0)
    lines = [
        "SITE CONTEXT REPORT EXPORT",
        "==========================",
        "",
        f"Centre (lon, lat): {lon:.6f}, {lat:.6f}",
        f"Square: {edge:.0f} m x {edge:.0f} m, aligned to true north",
        f"Coordinate system: {aoi.epsg} ({aoi.crs.name}); all units are metres.",
        f"Generated by sce {sce.__version__}.",
        "",
        "Files",
        "-----",
    ]
    for n in names:
        note = FILE_NOTES.get(n) or FILE_NOTES.get(Path(n).suffix, "")
        lines.append(f"{n}: {note}".rstrip(": "))
    lines += [
        "",
        "GLB and OBJ meshes are shifted to a local origin (float32 loses precision at",
        "projected-coordinate magnitudes). The origin is in georef.json, under",
        "local_origin: add it back to easting/northing to return to the CRS above.",
        "",
        "Data sources and licences",
        "-------------------------",
    ]
    sources = sources_of(layers)
    lines += [f"- {s['name']} ({s['licence']}) {s['url']}" for s in sources]
    if uses_odbl(sources):
        lines += ["", ODBL_NOTICE]
    return "\n".join(lines) + "\n"


def write_readme(path: str | Path, aoi: Any, layers: dict[str, LayerResult], names: list[str]) -> Path:
    """Write `readme_text` to `path`."""
    path = Path(path)
    path.write_text(readme_text(aoi, layers, names))
    return path
